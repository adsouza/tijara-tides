defmodule TijaraTidesWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :tijara_tides

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_tijara_tides_key",
    signing_salt: "BXNAi9y1",
    max_age: 365 * 24 * 60 * 60,
    same_site: "Lax",
    http_only: true,
    secure: Application.compile_env(:tijara_tides, :secure_cookies, false)
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Background music lives outside priv/static so phx.digest does not ship a
  # fingerprinted second copy of every recording. Range requests are served.
  plug :audio_content_type
  plug Plug.Static, at: "/audio", from: {:tijara_tides, "priv/audio"}, gzip: false

  # Serve at "/" the static files from "priv/static" directory.
  #
  # Only production serves the compressed files generated by `phx.digest`.
  # Elsewhere a leftover .gz would shadow the bundle that was just built.
  plug Plug.Static,
    at: "/",
    from: :tijara_tides,
    gzip: Application.compile_env(:tijara_tides, :gzip_static_assets, false),
    only: TijaraTidesWeb.static_paths(),
    only_matching: ["favicon-"],
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
  end

  plug TijaraTidesWeb.Plugs.ClientIp
  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug TijaraTidesWeb.Router

  # MIME 2.0 maps only .oga to audio/ogg, so label .ogg here, not in global config.
  defp audio_content_type(%Plug.Conn{path_info: ["audio" | _] = path} = conn, _opts) do
    if String.ends_with?(List.last(path), ".ogg"),
      do:
        Plug.Conn.register_before_send(
          conn,
          &Plug.Conn.put_resp_header(&1, "content-type", "audio/ogg")
        ),
      else: conn
  end

  defp audio_content_type(conn, _opts), do: conn
end
